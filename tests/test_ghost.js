const fs = require('fs');
const assert = require('assert');
const manifest = require('../manifest.json');
const js = fs.readFileSync(require('path').join(__dirname,'../bob.js'),'utf8');
const ghost = fs.readFileSync(require('path').join(__dirname,'../ghost.js'),'utf8');
assert.equal(manifest.manifest_version,3);
assert(manifest.content_scripts[1].js.indexOf('ghost.js') < manifest.content_scripts[1].js.indexOf('bob.js'));
assert(manifest.content_scripts[1].matches.includes('https://github.com/*'));
assert(js.includes('data-act="ghost"'));
assert(js.includes('data-act="ghostclear"'));
assert(js.includes('S.ghostContext.slice(0,5000)'));
assert(ghost.includes('window.BobGhost={inspect,clear,update'));
assert(ghost.includes('pointer-events:none'));
console.log('8 Ghost Tutor integration checks passed');
